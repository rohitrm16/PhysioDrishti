-- Run ONCE in the Supabase SQL Editor (after agent_voice_schema.sql). Safe to re-run.

alter table public.agent_bookings
  add column if not exists expires_at timestamptz,
  add column if not exists decided_by text,
  add column if not exists decided_at timestamptz,
  add column if not exists decision_reason text,
  add column if not exists proposed_at timestamptz,
  add column if not exists notified_at timestamptz,
  add column if not exists staff_note text;

create index if not exists agent_bookings_status_idx on public.agent_bookings (status, expires_at);

-- Audit trail: one row per action (who, what, when, why)
create table if not exists public.booking_events (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.agent_bookings(id) on delete cascade,
  action text not null,
  from_status text,
  to_status text,
  actor text not null,
  reason text,
  note text,
  slot_id bigint,
  created_at timestamptz not null default now()
);
create index if not exists booking_events_booking_idx on public.booking_events (booking_id, created_at);

-- Give older pending requests a deadline: 4 hours after creation or 2 hours before the slot, whichever is sooner
update public.agent_bookings b
set expires_at = least(b.created_at + interval '4 hours', s.starts_at - interval '2 hours')
from public.slots s
where s.id = b.slot_id and b.expires_at is null;

-- Server-only access (browser keys cannot read any of these)
alter table public.booking_events enable row level security;
grant select, insert, update, delete on public.booking_events, public.agent_bookings, public.slots to service_role;
grant usage, select on all sequences in schema public to service_role;
